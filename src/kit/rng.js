// Seeded randomness. Never Math.random in a composition: a frame must be the
// same bytes no matter which worker renders it or in which order.

/** 32-bit string hash (cyrb53 folded). */
export function hash(...parts) {
  const str = parts.map(String).join('␟');
  let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (h2 ^ h1) >>> 0;
}

/** mulberry32 generator → floats in [0,1). */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A generator keyed by the spec seed plus any labels: rng(seed, 'scramble', 3). */
export const rng = (seed, ...keys) => mulberry32(hash(seed, ...keys));

/** Stateless noise: same inputs → same float in [0,1). */
export const noise1 = (seed, ...keys) => hash(seed, ...keys) / 4294967296;

/** Seeded Fisher–Yates; returns a new array. */
export function shuffle(arr, rand) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
